#[test]
fn test_empty_module() {
    let py = compile_to_python("");
    assert!(py.contains("# Generated by tomc"));
    assert!(py.contains("from __future__ import annotations"));
}

#[test]
fn test_config_no_header() {
    let py = compile_to_python_no_header("");
    assert!(!py.contains("# Generated"));
    assert!(py.contains("from __future__ import annotations"));
}

#[test]
fn test_runtime_support_imported() {
    let py = compile_to_python_no_header("");
    assert!(py.contains("import sys as _sys"));
}

