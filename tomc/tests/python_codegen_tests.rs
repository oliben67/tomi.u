//! Python codegen tests for tomc

use tomc::codegen::{Backend, CodeGenerator, CodegenConfig};
use tomc::lexer::Lexer;
use tomc::parser::TomiParser;

/// Helper to compile tomi.u source to Python
fn compile_to_python(source: &str) -> String {
    let mut lexer = Lexer::new(source);
    let tokens = lexer.tokenize().expect("Lexer should succeed");
    let mut parser = TomiParser::new(tokens).with_source(source.to_string());
    let module = parser.parse().expect("Parser should succeed");

    let generator = CodeGenerator::new(Backend::Python);
    generator.generate(&module).expect("Codegen should succeed")
}

/// Helper to compile without header comments
fn compile_to_python_no_header(source: &str) -> String {
    let mut lexer = Lexer::new(source);
    let tokens = lexer.tokenize().expect("Lexer should succeed");
    let mut parser = TomiParser::new(tokens).with_source(source.to_string());
    let module = parser.parse().expect("Parser should succeed");

    let config = CodegenConfig { include_comments: false, ..CodegenConfig::default() };
    let generator = CodeGenerator::with_config(Backend::Python, config);
    generator.generate(&module).expect("Codegen should succeed")
}

